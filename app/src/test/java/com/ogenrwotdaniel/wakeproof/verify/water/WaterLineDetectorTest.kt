package com.ogenrwotdaniel.wakeproof.verify.water

import kotlin.math.abs
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * Two kinds of test, and the first kind is the important one.
 *
 * **Cross-language agreement.** The expected constants below were produced by
 * running the Python original over the *same pixels*
 * (`python -m waterline.portable_synth`). They are what proves the port is
 * faithful rather than merely plausible — a slipped variance or a lost half of
 * the band search leaves property tests passing and only shows up here.
 * Regenerate them whenever `tools/water/waterline/detect.py` changes; a
 * deliberate tuning change makes them stale, not wrong.
 *
 * **Properties.** The rest assert what the detector is *for*: a readable line
 * lands near the truth, an opaque flask is refused rather than guessed at.
 *
 * Neither kind is evidence about real photographs. A synthetic image contains
 * exactly the cues whoever wrote the generator thought to put in. The gate in
 * `docs/OFFLINE_WATER.md` has to be met on a real corpus, and until it is,
 * none of these numbers licence trusting the detector on its own.
 */
class WaterLineDetectorTest {

    private data class Expected(
        val line: Double,
        val fill: Double,
        val confidence: Double,
        val readable: Boolean
    )

    /** Generated by `python -m waterline.portable_synth`. */
    private val reference = mapOf(
        "clear_070" to Expected(line = 0.300836, fill = 0.699164, confidence = 535.8504, readable = true),
        "clear_035" to Expected(line = 0.643454, fill = 0.356546, confidence = 103.0996, readable = true),
        "dim_055" to Expected(line = 0.445682, fill = 0.554318, confidence = 99.4560, readable = true),
        "labelled_080" to Expected(line = 0.183844, fill = 0.816156, confidence = 126.0616, readable = true),
        "opaque_060" to Expected(line = 0.718663, fill = 0.281337, confidence = 2.6569, readable = false),
        "tinted_045" to Expected(line = 0.557103, fill = 0.442897, confidence = 61.8526, readable = true)
    )

    private fun scene(name: String): RgbImage = when (name) {
        "clear_070" -> PortableScene.render(fill = 0.70, seed = 1)
        "clear_035" -> PortableScene.render(fill = 0.35, seed = 1)
        "dim_055" -> PortableScene.render(fill = 0.55, seed = 2, brightness = 0.55)
        "labelled_080" -> PortableScene.render(fill = 0.80, seed = 3, withLabel = true)
        "opaque_060" -> PortableScene.render(fill = 0.60, seed = 4, opaque = true)
        "tinted_045" -> PortableScene.render(
            fill = 0.45, seed = 5, tint = Triple(0.72, 1.0, 0.78)
        )
        else -> error("unknown scene $name")
    }

    // --- the port matches the Python original ---------------------------------

    @Test
    fun `every reference scene reproduces Python's answer`() {
        reference.forEach { (name, expected) ->
            val observation = WaterLineDetector.detect(scene(name))
            assertEquals("$name line", expected.line, observation.line, 0.003)
            assertEquals("$name fill", expected.fill, observation.fill, 0.003)
            assertEquals("$name readable", expected.readable, observation.readable)
            // Confidence spans two orders of magnitude across these scenes, so
            // it is compared proportionally rather than absolutely.
            val relative = abs(observation.confidence - expected.confidence) /
                expected.confidence.coerceAtLeast(1.0)
            assertTrue(
                "$name confidence ${observation.confidence} vs ${expected.confidence}",
                relative < 0.02
            )
        }
    }

    @Test
    fun `the same-container score matches Python's`() {
        val pairs = listOf(
            Triple("clear_070", "clear_035", 1.000000),
            Triple("clear_070", "tinted_045", 0.225671),
            Triple("clear_070", "dim_055", 0.515535)
        )
        pairs.forEach { (firstName, secondName, expected) ->
            val before = scene(firstName)
            val after = scene(secondName)
            val first = WaterLineDetector.detect(before)
            val second = WaterLineDetector.detect(after)
            val match = ContainerMatcher.match(before, after, first.line, second.line)
            assertEquals("$firstName vs $secondName", expected, match.score, 0.01)
        }
    }

    // --- what the detector is for ---------------------------------------------

    @Test
    fun `a readable line lands within two percent of the truth`() {
        listOf(0.25, 0.40, 0.55, 0.70, 0.85).forEach { fill ->
            val observation = WaterLineDetector.detect(PortableScene.render(fill, seed = 9))
            assertTrue("fill $fill was called unreadable", observation.readable)
            assertEquals("fill $fill", fill, observation.fill, 0.02)
        }
    }

    @Test
    fun `an opaque flask is refused rather than guessed at`() {
        // No line exists at any price. Reporting one confidently is the failure
        // that silently accepts noise as a drink; saying "I cannot see it" is
        // the honest answer, and what levelReadable = false carries.
        val observation = WaterLineDetector.detect(
            PortableScene.render(fill = 0.60, seed = 4, opaque = true)
        )
        assertFalse(observation.readable)
        assertTrue(observation.confidence < WaterLineDetector.CONFIDENCE_FLOOR)
    }

    @Test
    fun `a printed label does not steal the line`() {
        // The label spans 30-46% of the height; the line sits at 20%. Locking
        // onto either label edge is the detector's worst single failure.
        val observation = WaterLineDetector.detect(
            PortableScene.render(fill = 0.80, seed = 3, withLabel = true)
        )
        assertEquals(0.80, observation.fill, 0.03)
    }

    @Test
    fun `a dim scene is still read`() {
        val observation = WaterLineDetector.detect(
            PortableScene.render(fill = 0.55, seed = 2, brightness = 0.55)
        )
        assertTrue(observation.readable)
        assertEquals(0.55, observation.fill, 0.02)
    }

    // --- the statistics, in isolation -----------------------------------------

    @Test
    fun `welch t finds a clean step`() {
        val profile = DoubleArray(100) { if (it < 50) 0.0 else 1.0 }
        val curve = WaterLineDetector.welchTCurve(profile, minSide = 5)
        var peak = 0
        for (i in curve.indices) if (curve[i] > curve[peak]) peak = i
        assertTrue(abs(peak - 50) <= 1)
        assertTrue("a noiseless step is arbitrarily significant", curve[peak] > 100)
    }

    @Test
    fun `welch t is flat on constant input`() {
        val curve = WaterLineDetector.welchTCurve(DoubleArray(100) { 0.4 }, minSide = 5)
        assertEquals(0.0, curve.max(), 1e-3)
    }

    @Test
    fun `welch t leaves min-side rows at zero`() {
        val profile = DoubleArray(100) { if (it < 50) 0.0 else 1.0 }
        val curve = WaterLineDetector.welchTCurve(profile, minSide = 10)
        for (i in 0 until 10) assertEquals(0.0, curve[i], 0.0)
        for (i in 91 until 100) assertEquals(0.0, curve[i], 0.0)
    }

    @Test
    fun `normalise maps a range onto zero to one and flattens a constant`() {
        val scaled = WaterLineDetector.normalise(doubleArrayOf(2.0, 4.0, 6.0))
        assertEquals(0.0, scaled[0], 1e-9)
        assertEquals(0.5, scaled[1], 1e-9)
        assertEquals(1.0, scaled[2], 1e-9)
        assertTrue(WaterLineDetector.normalise(DoubleArray(5) { 3.0 }).all { it == 0.0 })
    }

    @Test
    fun `the box blur replicates edges rather than fading to zero`() {
        val blurred = WaterLineDetector.boxBlurRows(DoubleArray(5) { 1.0 }, radius = 2)
        // A constant input must stay constant; padding with zeros instead of the
        // edge value would dip both ends and invent an edge at the crop boundary.
        assertTrue(blurred.all { abs(it - 1.0) < 1e-9 })
    }

    @Test
    fun `band suppression damps an edge with an opposite-signed partner`() {
        // A label: a step onto it and an opposite step off it, 20 rows apart.
        val height = 360
        val signed = DoubleArray(height)
        signed[100] = 10.0
        signed[120] = -10.0
        val suppressed = WaterLineDetector.suppressBands(signed, height)
        assertEquals(10.0 * WaterLineDetector.BAND_DAMPING, suppressed[100], 1e-9)
        assertEquals(10.0 * WaterLineDetector.BAND_DAMPING, suppressed[120], 1e-9)
    }

    @Test
    fun `band suppression searches upward as well as downward`() {
        // Looking only downward misses a label's BOTTOM edge, whose partner is
        // above it — the single worst failure mode this cue exists to fix.
        val height = 360
        val signed = DoubleArray(height)
        signed[100] = 10.0
        signed[130] = -10.0
        val suppressed = WaterLineDetector.suppressBands(signed, height)
        assertTrue("the lower edge must be damped too", suppressed[130] < 10.0)
    }

    @Test
    fun `a lone edge survives band suppression untouched`() {
        val height = 360
        val signed = DoubleArray(height)
        signed[200] = 7.0
        assertEquals(7.0, WaterLineDetector.suppressBands(signed, height)[200], 1e-9)
    }

    @Test
    fun `bottle columns discard the walls and keep the middle`() {
        val columns = WaterLineDetector.bottleColumns(200)
        assertEquals(30, columns.first)
        assertEquals(169, columns.last)
    }

    @Test
    fun `an image too small to profile is reported unreadable`() {
        val tiny = RgbImage(4, 4, IntArray(16))
        val observation = WaterLineDetector.detect(tiny)
        assertFalse(observation.readable)
        assertEquals(0.0, observation.confidence, 0.0)
    }
}
